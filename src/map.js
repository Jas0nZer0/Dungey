// Tile map. '#' is wall, '.' is floor.
export const map = [
  '####################',
  '#..................#',
  '#..####....####....#',
  '#..#..........#....#',
  '#..#..........#....#',
  '#..####....####....#',
  '#..................#',
  '#....#........#....#',
  '#....#........#....#',
  '#..................#',
  '#..................#',
  '#..................#',
  '#..................#',
  '#..................#',
  '####################',
].map((row) => row.split(''));

export const mapWidth = map[0].length;
export const mapHeight = map.length;

export function isFloor(x, y) {
  return map[y]?.[x] === '.';
}
